#!/usr/bin/env python3
"""
Мелодии напоминаний о приёме лекарств.

Почему генератор, а не готовые файлы: звук напоминания для пожилого человека —
не украшение, а рабочий инструмент, и подбирать его придётся на слух не один
раз. Здесь параметры каждой мелодии видны и правятся строкой, а не бинарным
редактором; собранные .wav лежат в `android/app/src/main/res/raw/` и в
репозиторий попадают уже собранными, чтобы сборка Android не требовала python.

Требования Android к мелодии канала: файл в `res/raw`, имя строчными буквами и
цифрами. Формат WAV выбран сознательно — играется без декодера, а размер здесь
роли не играет: две секунды моно занимают меньше сотни килобайт.

Запуск:  python3 tools/sounds.py
"""

import math
import struct
import wave
from pathlib import Path

ЧАСТОТА = 22050
КОРЕНЬ = Path(__file__).resolve().parent.parent
# Только ресурсы Android: мелодию играет система, а не страница. Копия рядом со
# страницей была нужна, пока «послушать» проигрывало файл плеером; от этого
# отказались — плеер идёт громкостью музыки и врёт о том, как прозвучит
# напоминание. Теперь проверка показывает настоящее уведомление.
ВЫХОД = КОРЕНЬ / 'android/app/src/main/res/raw'

# Ноты равномерного строя от ля первой октавы.
НОТЫ = {'до': 261.63, 'ре': 293.66, 'ми': 329.63, 'соль': 392.00, 'ля': 440.00,
        'до2': 523.25, 'ре2': 587.33, 'ми2': 659.25, 'соль2': 783.99, 'ля2': 880.00}


def колокольчик(нота: float, длительность: float, громкость: float = 0.9):
    """
    Один удар: основной тон плюс тихие обертоны, затухание по экспоненте.

    Чистая синусоида звучит как сигнал прибора и раздражает; пара обертонов
    делает звук похожим на колокольчик, который слышно, но от которого не
    вздрагиваешь.
    """
    кадров = int(ЧАСТОТА * длительность)
    for i in range(кадров):
        t = i / ЧАСТОТА
        затухание = math.exp(-3.2 * t / длительность)
        звук = (
            math.sin(2 * math.pi * нота * t)
            + 0.32 * math.sin(2 * math.pi * нота * 2 * t)
            + 0.12 * math.sin(2 * math.pi * нота * 3.01 * t)
        )
        # Первые пять миллисекунд — плавный вход, иначе в начале слышен щелчок.
        вход = min(1.0, t / 0.005)
        yield звук * затухание * вход * громкость / 1.44


def собрать(имя: str, фразы: list[tuple[str, float, float]]):
    """
    `фразы` — список (нота, когда начинается в секундах, сколько звучит).
    Ноты накладываются друг на друга, поэтому переливы получаются связными.
    """
    длина = max(нач + дл for _, нач, дл in фразы)
    буфер = [0.0] * int(ЧАСТОТА * (длина + 0.25))
    for нота, начало, длительность in фразы:
        сдвиг = int(ЧАСТОТА * начало)
        for i, v in enumerate(колокольчик(НОТЫ[нота], длительность)):
            if сдвиг + i < len(буфер):
                буфер[сдвиг + i] += v

    пик = max(abs(v) for v in буфер) or 1.0
    данные = b''.join(struct.pack('<h', int(max(-1.0, min(1.0, v / пик * 0.86)) * 32767)) for v in буфер)

    ВЫХОД.mkdir(parents=True, exist_ok=True)
    путь = ВЫХОД / f'{имя}.wav'
    with wave.open(str(путь), 'wb') as f:
        f.setnchannels(1)
        f.setsampwidth(2)
        f.setframerate(ЧАСТОТА)
        f.writeframes(данные)
    return путь, len(данные) // 2 / ЧАСТОТА


МЕЛОДИИ = {
    # Два мягких удара — ни на что в телефоне не похоже, но не пугает.
    'myagkiy': [('соль', 0.00, 1.5), ('до2', 0.28, 1.7)],
    # Восходящая тройка: слышно даже вполуха, читается как «внимание».
    'kolokolchik': [('до2', 0.00, 1.1), ('ми2', 0.20, 1.1), ('соль2', 0.40, 1.8)],
    # Длинный перелив для тех, кто плохо слышит высокие: держится дольше.
    'pereliv': [('до', 0.00, 2.2), ('соль', 0.22, 2.0), ('до2', 0.44, 2.0), ('ми2', 0.66, 2.4)],
}

if __name__ == '__main__':
    for имя, фразы in МЕЛОДИИ.items():
        путь, секунд = собрать(имя, фразы)
        print(f'{путь.name:16} {секунд:.2f} с  {путь.stat().st_size / 1024:.0f} КБ')
