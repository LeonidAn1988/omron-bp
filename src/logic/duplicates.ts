/**
 * Одно и то же действующее вещество в двух коробках.
 *
 * У пожилого человека назначения от терапевта, кардиолога и невролога, и
 * каждый выписывает своё. Торговые названия разные, вещество одно — это самая
 * обычная домашняя ошибка, и находят её обычно случайно, уже на приёме.
 *
 * Данные для сверки в аптечке лежат: поле `inn` подставляется из ГРЛС при
 * выборе препарата. Их просто никто не сводил между собой.
 *
 * **Где здесь черта.** Приложение сообщает факт о собственном списке человека
 * и на этом останавливается: «вещество то же». Ни «опасно», ни «отмените
 * одно» — врач мог назначить так намеренно (например, разные формы или разное
 * время суток), и решать это не приложению. Как только появится оценка, мы
 * перестанем быть дневником и станем медизделием — черта та же, что в §11
 * бэклога.
 */

import type { Medicine } from '../types'

/**
 * Разложить строку вещества на отдельные вещества.
 *
 * У комбинированных препаратов в реестре стоит «Амлодипин + Периндоприл», а
 * иногда «амлодипин, индапамид». Без разбора совпадение с одиночным
 * «Амлодипином» не нашлось бы вовсе — а это ровно тот случай, ради которого
 * всё и делается: одно вещество человек получает дважды, из комбинации и
 * отдельно.
 */
export function substances(inn: string | undefined): string[] {
  if (!inn) return []
  return inn
    .split(/[+,;/]/)
    .map((part) =>
      part
        .toLowerCase()
        .replace(/\([^)]*\)/g, ' ')
        .replace(/[^а-яёa-z0-9-]+/g, ' ')
        .trim(),
    )
    .filter((part) => part.length >= 4)
}

/** Торговое имя для сравнения: регистр и знаки охраны роли не играют. */
const имя = (name: string) => name.toLowerCase().replace(/[®™©]/g, '').replace(/\s+/g, ' ').trim()

/** Совпадение: у этой коробки то же вещество, что у другой. */
export interface SameSubstance {
  /** С чем совпало — имена других коробок. */
  others: string[]
  /** Какое вещество общее. */
  substance: string
}

/**
 * Найти для каждой коробки те, у которых есть общее вещество.
 *
 * Ключ — идентификатор коробки. Коробки без вещества и одиночки в ответ не
 * попадают: говорить не о чем.
 */
export function sameSubstance(medicines: Medicine[]): Map<string, SameSubstance> {
  const поВеществу = new Map<string, Medicine[]>()
  for (const medicine of medicines) {
    for (const вещество of substances(medicine.inn)) {
      const bucket = поВеществу.get(вещество)
      if (bucket) bucket.push(medicine)
      else поВеществу.set(вещество, [medicine])
    }
  }

  const итог = new Map<string, SameSubstance>()
  for (const [вещество, группа] of поВеществу) {
    if (группа.length < 2) continue
    for (const medicine of группа) {
      // Соседи по веществу — но только под **другим** торговым именем.
      //
      // Две коробки одного препарата (докупили новую пачку) веществом,
      // разумеется, совпадают, но пункт не про них: «вещество то же, что у
      // „Конкор“» на карточке самого Конкора человека только запутает, а обе
      // пачки он и так видит в списке рядом.
      const своё = имя(medicine.name)
      const другие = [
        ...new Set(группа.filter((item) => имя(item.name) !== своё).map((item) => item.name)),
      ]
      if (другие.length === 0) continue
      // Уже нашли совпадение по другому веществу — первое и оставляем: две
      // строки под одной коробкой человек читать не станет.
      if (итог.has(medicine.id)) continue
      итог.set(medicine.id, { others: другие, substance: вещество })
    }
  }
  return итог
}

/** Строка для человека. Только факт, без оценки и без совета. */
export function sameSubstanceText(match: SameSubstance): string {
  const кто = match.others.length === 1 ? `«${match.others[0]}»` : match.others.map((n) => `«${n}»`).join(', ')
  return `Действующее вещество то же, что у ${кто} — ${match.substance}`
}
