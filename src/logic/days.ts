/**
 * Календарные сутки.
 *
 * Не деление метки времени на 86 400 000. В ночь перевода часов сутки длятся
 * двадцать три часа или двадцать пять, и деление либо схлопывает два местных
 * дня в один, либо теряет день целиком. Для напоминаний это значит, что
 * идентификаторы за разные дни совпадут и одно снимет другое.
 *
 * Собрано в отдельный модуль, потому что этими же сутками считают и аптечка, и
 * планировщик напоминаний, и расписание измерений — а импортировать их друг у
 * друга значит завести кольцо.
 */

const СУТКИ = 86_400_000

/** Начало дня по местному времени: сроки и расписания — про дни, не про часы. */
export function startOfDay(ts: number): number {
  const d = new Date(ts)
  d.setHours(0, 0, 0, 0)
  return d.getTime()
}

/**
 * Номер суток по местному календарю.
 *
 * Через `Date.UTC` от местных год-месяц-день: так номер получается устойчивым к
 * переводу часов, а соседние местные дни никогда не попадают в одну ячейку.
 */
export function dayNumber(ts: number): number {
  const d = new Date(ts)
  return Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / СУТКИ)
}

/** Местная полночь дня, отстоящего от `from` на `сдвиг` календарных суток. */
export function addDays(from: Date, сдвиг: number): Date {
  const d = new Date(from)
  d.setDate(d.getDate() + сдвиг)
  // Ещё раз к полуночи: в ночь перевода часов сложение дат оставляет час-другой.
  d.setHours(0, 0, 0, 0)
  return d
}

/** Момент внутри дня как местное время, а не «полночь плюс минуты». */
export function momentOf(день: Date, минуты: number): number {
  return new Date(
    день.getFullYear(),
    день.getMonth(),
    день.getDate(),
    Math.floor(минуты / 60),
    минуты % 60,
    0,
    0,
  ).getTime()
}

/**
 * Сколько календарных суток между днями.
 *
 * Округление, а не отбрасывание дробной части: между двумя полуночами через
 * перевод часов лежит 23 или 25 часов, и `floor` дал бы на день меньше.
 */
export function daysBetween(from: number, to: number): number {
  return Math.round((startOfDay(to) - startOfDay(from)) / СУТКИ)
}
