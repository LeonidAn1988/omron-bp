/**
 * Сколько осталось в памяти прибора.
 *
 * Тонометр держит сто записей на каждую свою кнопку — и это **кольцевой
 * буфер**: когда сотня набралась, прибор начинает молча затирать самое старое.
 * Молча — ключевое слово. Приложение вычитывает память целиком и получает уже
 * урезанное, а отличить «столько и было» от «часть уже съедена» по самим
 * записям нельзя.
 *
 * Цена ошибки видна на живом сценарии. Пожилой человек выгружает раз в
 * квартал — перед приёмом у врача. Меряет трижды в день. Сотня набивается за
 * тридцать три дня, и к врачу он приносит месяц вместо трёх, не подозревая об
 * этом. Строка «Прочитано из памяти прибора: 100», которая стояла здесь
 * раньше, об этом не говорила ничего.
 *
 * Здесь нет ни Bluetooth, ни разметки — только счёт, поэтому это проверяется
 * обычными тестами.
 */

import { plural } from './plural'

/** Сколько записей прибор держит на одну свою кнопку. */
export const DEVICE_SLOTS = 100

/** Что известно про память одной кнопки прибора. */
export interface MemoryUse {
  /** Кнопка прибора: 1 или 2. */
  user: number
  /** Сколько слотов занято. */
  used: number
  /** Сколько всего слотов. */
  capacity: number
  /** Память заполнена — прибор уже затирает самое старое. */
  full: boolean
  /**
   * За сколько дней прибор наберёт оставшееся при нынешнем темпе.
   * `null` — темп посчитать не из чего: меньше двух записей или все в один день.
   */
  daysLeft: number | null
  /** Замеров в день по прочитанному. `null` — считать не из чего. */
  perDay: number | null
}

/** Запись прибора глазами этого расчёта: чья кнопка и когда. */
export interface MemoryRecord {
  user: number
  ts: number
}

const DAY = 24 * 60 * 60 * 1000

/**
 * Разобрать прочитанное по кнопкам прибора.
 *
 * Считаем по каждой кнопке отдельно, а не в сумме. У прибора их две, у второго
 * человека своя сотня, и «занято 96» в сумме не значит ничего: это может быть
 * 96 и 0, а может 48 и 48. Человек смотрит на свою.
 */
export function memoryUse(records: MemoryRecord[], capacity = DEVICE_SLOTS): MemoryUse[] {
  const byUser = new Map<number, number[]>()
  for (const record of records) {
    const bucket = byUser.get(record.user)
    if (bucket) bucket.push(record.ts)
    else byUser.set(record.user, [record.ts])
  }

  return [...byUser.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([user, stamps]) => {
      const used = stamps.length
      const first = Math.min(...stamps)
      const last = Math.max(...stamps)
      // Темп берём по самому прибору, а не по дневнику: в дневнике могут
      // лежать записи, введённые руками, и они память прибора не занимают.
      //
      // Считаем по числу охваченных дней, а не по промежутку между крайними
      // записями. Разница не придирка: тридцать записей по одной в день лежат
      // в промежутке двадцать девять дней, и деление на него давало темп
      // 1,03 в день вместо ровно единицы — а из него уже неверный ответ на
      // вопрос «на сколько ещё хватит».
      const дней = Math.round((last - first) / DAY) + 1
      // Меньше двух дней наблюдения — темпа нет. Три замера, снятые подряд в
      // один вечер, дали бы «три в день», и совет вышел бы из воздуха.
      const perDay = used >= 2 && дней >= 2 ? used / дней : null
      const left = Math.max(0, capacity - used)
      return {
        user,
        used,
        capacity,
        full: used >= capacity,
        perDay,
        daysLeft: perDay === null || perDay <= 0 ? null : Math.floor(left / perDay),
      }
    })
}

/**
 * Что сказать человеку про его память прибора.
 *
 * Совет здесь ровно один — «выгрузите», — и другого быть не может: память
 * прибора приложение не чистит, в прибор вообще ничего не пишется, кроме ключа
 * сопряжения.
 */
export function memoryHint(use: MemoryUse): string {
  if (use.full) {
    // Не «у вас всё пропало»: часть могла и не пропасть, если человек выгружал
    // раньше — старое уже лежит в дневнике. Говорим только то, что знаем.
    return `Занято ${use.used} из ${use.capacity} — память заполнена, и прибор уже затирает самое старое. Выгружайте почаще: то, что он сотрёт до следующей выгрузки, не вернуть.`
  }
  const хвост =
    use.daysLeft === null
      ? ''
      : use.daysLeft <= 7
        ? ` Свободного места примерно на ${use.daysLeft} ${plural(use.daysLeft, 'день', 'дня', 'дней')} при нынешнем темпе.`
        : ` При нынешнем темпе места хватит примерно на ${Math.round(use.daysLeft / 7)} ${plural(Math.round(use.daysLeft / 7), 'неделю', 'недели', 'недель')}.`
  return `Занято ${use.used} из ${use.capacity}.${хвост}`
}

/** Пора ли поторопиться с выгрузкой. */
export function memoryTight(use: MemoryUse): boolean {
  return use.full || (use.daysLeft !== null && use.daysLeft <= 14)
}
