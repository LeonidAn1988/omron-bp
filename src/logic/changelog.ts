/**
 * История изменений — из `CHANGELOG.md`, а не из кода.
 *
 * Источник один. Заводить рядом с файлом ещё и константу с номером версии
 * значит завести два источника, которые разойдутся в первый же выпуск: правку
 * в одном месте забудут ровно тогда, когда версия важнее всего. Поэтому номер
 * текущей версии берётся из верхней записи того же файла, а совпадение с
 * `versionName` в `android/app/build.gradle` стережёт автопроверка.
 *
 * Разбор нарочно строгий и без библиотеки markdown: формат свой, короткий и
 * описан в шапке самого `CHANGELOG.md`. Тянуть ради него парсер в бандл, куда
 * и так уложены 35 тысяч наименований лекарств, незачем.
 */

export interface Release {
  /** Номер версии, как в `versionName`: `0.4.0`. */
  version: string
  /** Дата словами, как её написали в файле: «1 сентября 2026». */
  date: string
  /** Строки списка. Короткие предложения, готовые к показу. */
  items: string[]
}

/**
 * Разобрать файл истории.
 *
 * Записи возвращаются в том порядке, в каком лежат в файле, — то есть новая
 * первой. Заголовок без списка пропускается: пустая версия в интерфейсе
 * выглядит поломкой, а не отсутствием изменений.
 */
export function parseChangelog(source: string): Release[] {
  const releases: Release[] = []
  let current: Release | null = null

  for (const raw of source.split('\n')) {
    // Отступ слева не срезаем: именно он превращает пример формата в шапке
    // файла в блок кода. Срезав его, разбор принимал пояснение для того, кто
    // правит файл, за настоящую запись — и «Что изменилось» открывалось
    // инструкцией по заполнению.
    const line = raw.trimEnd()

    const heading = /^##[ \t]+(\S+)[ \t]+—[ \t]+(.+)$/.exec(line)
    if (heading) {
      if (current && current.items.length) releases.push(current)
      current = { version: heading[1], date: heading[2].trim(), items: [] }
      continue
    }

    // Список читаем только внутри записи: строки из шапки файла — пояснение
    // для того, кто её правит, а не для того, кто читает приложение.
    if (current && /^-[ \t]/.test(line)) current.items.push(line.slice(1).trim())
  }
  if (current && current.items.length) releases.push(current)

  return releases
}

/** Текущая версия — верхняя запись. Пустая строка, если файл ещё не заполнен. */
export function currentVersion(releases: Release[]): string {
  return releases[0]?.version ?? ''
}
