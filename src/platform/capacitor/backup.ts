/**
 * Автоматические копии на Android.
 *
 * Копия имеет смысл, только если её можно вернуть. Первая версия этого файла
 * писала в `Directory.Data` — приватный каталог приложения, куда не заглядывает
 * ни файловый менеджер, ни системный выбор файла, через который в приложении
 * устроено восстановление. Получалась копия, которую невозможно достать: она
 * гасила предупреждение «копии нет», но не спасала ни от чего, кроме сбоя
 * самого приложения. Теперь файл лежит в каталоге приложения на общей памяти —
 * `Android/data/<приложение>/files`. Оттуда его видно и файловым менеджером, и
 * системным выбором файла при восстановлении.
 *
 * Чего это по-прежнему не отменяет: файл остаётся **внутри телефона**. Он
 * переживает перезагрузку и обновление приложения, но исчезает вместе с ним при
 * удалении, а с потерянным телефоном пропадает целиком. Поэтому отправка копии
 * наружу через «поделиться» остаётся обязательной частью сценария, и интерфейс
 * продолжает об этом напоминать.
 */

import { Directory, Encoding, Filesystem } from '@capacitor/filesystem'
import type { BackupPort } from '../ports'

/**
 * `External` — каталог приложения на общей памяти. Не `Data`: оттуда файл не
 * достать. И не общие «Документы»: дневник давления не должен лежать там, где
 * его увидит любое приложение с доступом к хранилищу.
 */
const DIR = Directory.External
const FILE = 'дневник-копия.json'
/**
 * Пишем сначала во временный файл, потом переименовываем поверх.
 *
 * `writeFile` усекает файл до записи первого байта. Если на середине кончится
 * место или система убьёт приложение, на диске останется обрезанный JSON — то
 * есть копия, которая не читается, вместо прежней, которая читалась. Обмен
 * через переименование делает подмену мгновенной: целым остаётся либо старый
 * файл, либо новый.
 */
const TEMP = 'дневник-копия.tmp'

/** Согласие на автокопии. Хранится отдельно: файла до первой записи ещё нет. */
const ENABLED_KEY = 'omron.backup-enabled'

const enabled = (): boolean => {
  try {
    return localStorage.getItem(ENABLED_KEY) === '1'
  } catch {
    return false
  }
}

const setEnabled = (value: boolean) => {
  try {
    if (value) localStorage.setItem(ENABLED_KEY, '1')
    else localStorage.removeItem(ENABLED_KEY)
  } catch {
    // Без памяти под флаг автокопии просто не включатся — данные не пострадают.
  }
}

export const capacitorBackup: BackupPort = {
  /**
   * На Android автоматических копий пока нет — и это осознанный отказ.
   *
   * Копия имеет смысл, только если её можно вернуть. Писать без спроса
   * приложение может лишь в свои каталоги: приватный не виден никому, а
   * `Android/data` с одиннадцатой версии закрыт и для файловых менеджеров, и
   * для системного выбора файла, через который в приложении устроено
   * восстановление. Значит, автоматически записанный файл человек не достанет —
   * ни на другое устройство, ни после сброса телефона.
   *
   * Хуже, что такая копия **гасит предупреждение** «копии нет» и создаёт
   * ложное спокойствие ровно там, где приложение обещает обратное.
   *
   * Правильное решение — Storage Access Framework: человек один раз указывает
   * файл, система выдаёт долгоживущее разрешение, и дальше приложение пишет
   * туда само. Это ровно то, что делает File System Access API в вебе. Плагин
   * файлов такого не умеет, нужен свой — отдельная работа.
   *
   * Пока же остаётся ручной путь, и он полноценный: кнопка «Отправить копию»
   * отдаёт файл системному окну, откуда он уходит в облако, мессенджер или
   * почту — то есть **за пределы телефона**, чего автокопия не давала бы вовсе.
   * Реализация ниже оставлена рабочей и ждёт SAF.
   */
  isSupported() {
    return false
  },

  /**
   * Диалога выбора файла нет и не нужно: место известно заранее.
   *
   * Ничего не пишем — только запоминаем согласие. Прежняя версия создавала здесь
   * пустой файл «чтобы человек увидел результат», и получалось хуже: на диске
   * лежал пустой файл, а очередная запись откладывалась до следующего
   * измерения, потому что дневник ещё не разошёлся со счётчиком. Всё это время
   * приложение утверждало, что копии идут.
   */
  async choose() {
    setEnabled(true)
    return FILE
  },

  async target() {
    return enabled() ? FILE : null
  },

  async write(content) {
    if (!enabled()) return false
    try {
      await Filesystem.writeFile({ path: TEMP, data: content, directory: DIR, encoding: Encoding.UTF8 })
      // Переименование поверх существующего файла: у плагина это атомарная
      // замена, промежуточного состояния «файла нет» не возникает.
      await Filesystem.rename({ from: TEMP, to: FILE, directory: DIR, toDirectory: DIR })
      return true
    } catch {
      // Место кончилось, каталог недоступен, память отключили. Молча теряться
      // нельзя: приложение по false покажет предупреждение.
      try {
        await Filesystem.deleteFile({ path: TEMP, directory: DIR })
      } catch {
        // Обрывок временного файла не мешает: следующая запись его перезапишет.
      }
      return false
    }
  },

  /**
   * Забыть цель. Файл **не удаляем**: он единственная копия дневника на этом
   * телефоне, и стирать его по нажатию «отключить автокопии» — не то, чего
   * человек просил. В вебе этот метод тоже только забывает описатель.
   */
  async forget() {
    setEnabled(false)
  },
}
