/**
 * «Назад» на Android.
 *
 * Истории WebView приложение не ведёт вовсе, и это не упрощение, а
 * необходимость. Пока подписан слушатель `backButton`, WebView сам назад не
 * ходит: плагин перехватывает нажатие и отдаёт его нам. А `canGoBack`, который
 * плагин присылает вместе с событием, — состояние списка навигации самого
 * WebView, и приложение им не управляет: любая навигация на месте сделает его
 * истинным, и «Назад» на корне уведёт человека с приложения на пустую
 * страницу. Отказ при этом бесшумный и от поломки телефона неотличим.
 *
 * Поэтому глубину знает только приложение, а платформа делает одно: приносит
 * нажатие и сворачивает приложение, когда снимать больше нечего. Свёрнутое
 * открывается мгновенно и с того же места — это не то же самое, что закрытое.
 */

import { App } from '@capacitor/app'
import type { NavPort } from '../ports'

let обработчик: (() => boolean) | null = null

export const capacitorNav: NavPort = {
  onBack(handler) {
    обработчик = handler
    return () => {
      if (обработчик === handler) обработчик = null
    }
  },

  /** Историю не ведём: см. заголовок файла. */
  sync() {},

  back() {
    if (!обработчик?.()) void App.minimizeApp()
  },
}

export function installBackButton() {
  // Второй канал того же нажатия — событие `backbutton` на документе, которое
  // плагин шлёт следом. Подписываться на него нельзя: одно нажатие сняло бы
  // сразу два уровня.
  void App.addListener('backButton', () => capacitorNav.back())
}
