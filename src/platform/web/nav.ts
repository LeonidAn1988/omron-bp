/**
 * «Назад» в браузере.
 *
 * Глубина экранов зеркалится в историю страницы: на каждый уровень — одна
 * запись. Тогда работает и стрелка браузера, и системная кнопка в приложении,
 * добавленном на домашний экран, — там «назад» это ровно `history.back()`, и
 * без записей она закрывала бы приложение из середины настроек.
 *
 * Адрес при этом не меняется. Сборка живёт по относительному пути, а служебный
 * работник обрабатывает переходы; менять URL значило бы трогать и то и другое
 * ради счётчика, который приложение и так держит у себя.
 */

import type { NavPort } from '../ports'

let обработчик: (() => boolean) | null = null
let глубина = 0

/**
 * Есть ли вообще история страницы.
 *
 * Ядро с этой платформой поднимают и вне браузера — так проверяются миграции
 * хранилища. Там ни `window`, ни `history` нет, и зеркалить глубину некуда;
 * приложение при этом работает: стек живёт в нём самом, а история — только
 * удобство для браузерной стрелки.
 */
const естьИстория = () => typeof window !== 'undefined'

/** Своя запись в истории: чужие (например, от расширений) не трогаем. */
type Метка = { omron?: number }

export const webNav: NavPort = {
  onBack(handler) {
    обработчик = handler
    return () => {
      if (обработчик === handler) обработчик = null
    }
  },

  sync(next) {
    if (!естьИстория()) return
    const было = глубина
    // Переменную двигаем первой: `history.go` вызовет `popstate` асинхронно, и
    // слушатель должен увидеть уже новую глубину, иначе примет собственную
    // отмотку за нажатие человека и снимет ещё один уровень.
    глубина = next
    if (next > было) {
      for (let i = было; i < next; i++) history.pushState({ omron: i + 1 } satisfies Метка, '')
    } else if (next < было) {
      history.go(next - было)
    }
  },

  back() {
    обработчик?.()
  },
}

export function installWebBack() {
  if (!естьИстория()) return
  window.addEventListener('popstate', (event) => {
    const метка = (event.state as Метка | null)?.omron ?? 0
    // «Вперёд» и чужие записи не наши: приложение вперёд не ходит.
    if (метка >= глубина) return
    // История уже там, где нужно; догонять её не надо, только состояние.
    глубина = метка
    обработчик?.()
  })
}
