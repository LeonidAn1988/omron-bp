/**
 * Модель измерений.
 *
 * Размеченное объединение, а не один тип со всеми полями сразу: давление и сахар
 * измеряются разными приборами, интерпретируются по разным правилам и почти не
 * имеют общих полей, кроме «когда» и «чьё».
 *
 * Датчики непрерывного мониторинга сюда сознательно НЕ добавлены отдельным видом:
 * они дают запись каждые 1–5 минут, то есть ~288 значений в сутки против трёх у
 * тонометра. Это не «ещё один источник», а другая форма данных — ей нужны своё
 * хранилище и прореживание при отрисовке, иначе список и графики не выдержат.
 * Расширять `MeasurementKind` под них нельзя: разметка обязана остаться про
 * дискретные замеры. Подробности — в BACKLOG.md, пункты 3 и 4.
 */

export type MeasurementSource = 'device' | 'manual' | 'import'

export type MeasurementKind = 'bp' | 'glucose'

interface MeasurementBase {
  /** Для записей с прибора — детерминированный, чтобы повторная выгрузка не плодила дубли. */
  id: string
  /** Момент измерения, epoch ms. */
  ts: number
  /** Пользователь прибора: 1 или 2. */
  user: number
  source: MeasurementSource
  note?: string
}

export interface BpReading extends MeasurementBase {
  kind: 'bp'
  /** Систолическое, мм рт. ст. */
  sys: number
  /** Диастолическое, мм рт. ст. */
  dia: number
  bpm: number | null
  /** Нерегулярное сердцебиение (по данным прибора). */
  ihb: boolean
  /** Движение во время измерения (по данным прибора). */
  mov: boolean
  arm?: 'left' | 'right'
}

/**
 * Момент замера относительно еды. Обязателен: значение глюкозы без него
 * не интерпретируется — 9 ммоль/л натощак и через два часа после еды значат разное.
 */
export type GlucoseContext = 'fasting' | 'before-meal' | 'after-meal' | 'bedtime' | 'night'

export const GLUCOSE_CONTEXT_LABELS: Record<GlucoseContext, string> = {
  fasting: 'Натощак',
  'before-meal': 'До еды',
  'after-meal': 'Через 2 часа после еды',
  bedtime: 'Перед сном',
  night: 'Ночью',
}

export interface GlucoseReading extends MeasurementBase {
  kind: 'glucose'
  /** Концентрация глюкозы, ммоль/л — единица, принятая в России и Европе. */
  mmol: number
  context: GlucoseContext
}

export type Measurement = BpReading | GlucoseReading

export const isBp = (m: Measurement): m is BpReading => m.kind === 'bp'
export const isGlucose = (m: Measurement): m is GlucoseReading => m.kind === 'glucose'

/**
 * Препарат в аптечке.
 *
 * Это не измерение: у него нет момента времени, он не попадает в графики и не
 * участвует в статистике. Поэтому отдельный тип и отдельное хранилище, а не
 * ещё один вид в объединении Measurement.
 *
 * Расписание приёма и отметки о принятых дозах хранятся здесь же. Напоминания
 * в заданное время браузер не умеет — планировщика в вебе нет; поэтому
 * расписание выгружается в системный календарь телефона, а он и напоминает.
 */
export interface Medicine {
  id: string
  /** Название с упаковки. */
  name: string
  /** Дозировка как написано на коробке: «5 мг», «10 мг/мл». Свободный текст: вариантов слишком много. */
  dose: string
  /**
   * Лекарственная форма: таблетки, капсулы, капли глазные.
   *
   * Подставляется из реестра. Отдельно от дозировки, потому что одна и та же
   * цифра у разных форм значит разное: «5 %» у геля и «5 мг» у таблеток.
   */
  form?: string
  /**
   * Международное непатентованное наименование. Подставляется из реестра.
   * Нужно там, где врач называет препарат одним словом, а на упаковке
   * напечатано торговое название другой фирмы.
   */
  inn?: string
  /** Остаток в таблетках, ампулах, дозах. `null` — не считаем этот препарат. */
  left: number | null
  /** Сколько уходит в сутки. Нужно ровно для одного — предсказать, на сколько дней хватит. */
  perDay: number | null
  /** Срок годности. `null` — не указан. */
  expires: number | null
  note?: string

  /** Производитель или держатель регистрационного удостоверения. Из реестра. */
  maker?: string
  /** Сколько штук в упаковке. Нужно кнопке «Купил упаковку» и списку покупок. */
  packSize?: number
  /** Номер регистрационного удостоверения — по нему ищется официальная инструкция. */
  regNumber?: string

  /**
   * Когда остаток подтверждали последний раз.
   *
   * Без этого «хватит на 28 дней» устаревало со второго дня: остаток менялся
   * только вручную, а предупреждение «пора заказывать» не срабатывало никогда.
   */
  leftAt?: number

  /**
   * Время приёмов: «08:00», «20:00». Пусто — препарат по потребности,
   * напоминать не о чем и в расписание он не идёт.
   */
  times?: string[]
  /** Сколько штук за один приём. По умолчанию одна. */
  perTime?: number
  /** Когда принимать относительно еды. Влияет только на подпись напоминания. */
  meal?: 'before' | 'after' | 'any'

  /**
   * Списывать остаток по расписанию, не дожидаясь подтверждения.
   *
   * Нажимать «Принял» трижды в день согласится не всякий, а несписанный
   * остаток врёт и предупреждение о том, что пора покупать, не приходит.
   * Здесь приложение считает, что назначенное принято, и говорит об этом
   * прямо. Отметки приёма при этом остаток не трогают — иначе списалось бы
   * дважды.
   */
  autoDeduct?: boolean

  /**
   * Отметки о принятых дозах. Хранится только недавнее — по этим меткам видно,
   * принято ли сегодня, а история приёма за годы никому не нужна и раздувает
   * резервную копию.
   */
  taken?: number[]
}

/** Оформление. «Как в системе» — значение по умолчанию, оно же поведение до этой настройки. */
export type ThemeChoice = 'auto' | 'light' | 'dark'

/**
 * Разделы нижней навигации.
 *
 * Отец ведёт все три дневника, сыну нужны только лекарства. Состав панели —
 * личная настройка: он меняется прямым действием и никогда сам по себе.
 * Появляющиеся и исчезающие вкладки сбивают с толку сильнее, чем лишний пункт.
 */
export interface SectionVisibility {
  bp: boolean
  glucose: boolean
  intake: boolean
  cabinet: boolean
}

/** Ключи разделов приложения. Обзор и настройки скрыть нельзя. */
export type SectionKey = keyof SectionVisibility

export interface Settings {
  /** Ключ сопряжения, 32 hex-символа. */
  pairingKey: string
  /** Как подписаны пользователи прибора. */
  userNames: Record<number, string>
  /** Активный пользователь, чьи данные показываем. */
  activeUser: number

  /** Целевое давление, назначенное врачом. */
  targetSys: number
  targetDia: number

  /** Верхняя граница нормы натощак и до еды, ммоль/л. */
  glucoseFastingMax: number
  /** Верхняя граница нормы через 2 часа после еды, ммоль/л. */
  glucosePostMealMax: number
  /** Порог гипогликемии, ммоль/л. */
  glucoseLow: number

  /** Показывать ли раздел сахара. Включается сам, как только появляется первая запись. */
  trackGlucose: boolean

  /** Светлая или тёмная тема. */
  theme: ThemeChoice

  /** Какие разделы показывать в нижней навигации. */
  sections: SectionVisibility
  /** С какого экрана открывается приложение. */
  startTab: string

  /** Когда сделана последняя резервная копия. null — не делалась. */
  backupLastAt: number | null
  /** Сколько записей вошло в последнюю копию: по расхождению видно, что она устарела. */
  backupLastCount: number
}
