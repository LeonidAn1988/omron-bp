/**
 * Поиск по справочнику ГРЛС.
 *
 * Проверяется на настоящих названиях из реестра: реестр пишет «Аспирин® Кардио»
 * и «Престариум® А», а человек набирает «аспирин кардио» строчными и без знака.
 */
import { normalize, searchDrugs, describeDrug, variantsOf } from './build/api.mjs'

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const формы = ['Таблетки', 'Капсулы', 'Гель для наружного применения']
  const книга = [
    { n: 'Аспирин®', i: 'Ацетилсалициловая кислота', v: [[0, ['500 мг']]] },
    { n: 'Аспирин® Кардио', i: 'Ацетилсалициловая кислота', v: [[0, ['100 мг']]] },
    { n: 'Кардиомагнил', i: 'Ацетилсалициловая кислота+[Магния гидроксид]', v: [[0, ['75 мг']]] },
    { n: 'Лозартан', i: 'Лозартан', v: [[0, ['12,5 мг', '25 мг', '50 мг', '100 мг']]] },
    { n: 'Престариум® А', i: 'Периндоприл', v: [[0, ['5 мг', '10 мг']]] },
    { n: 'Метформин-Тева', i: 'Метформин', v: [[0, ['500 мг']]] },
    { n: 'Валидол', i: 'Левоментола раствор в ментилизовалерате', v: [[0, ['60 мг']]] },
    { n: 'Нурофен® Экспресс', i: 'Ибупрофен', v: [[1, ['200 мг']], [0, ['200 мг']], [2, ['5 %']]] },
  ]

  // ── приведение к сравнимому виду ─────────────────────────────────────────
  check('знак охраны товарного знака отбрасывается', normalize('Аспирин®') === 'аспирин')
  check('регистр не важен', normalize('ЛОЗАРТАН') === 'лозартан')
  check('ё приравнена к е', normalize('Тёва') === normalize('Тева'))
  check('дефисы и пробелы схлопываются', normalize('Метформин-Тева') === 'метформин тева')
  check('латиница сохраняется', normalize('L-Тироксин') === 'l тироксин')

  // ── поиск ────────────────────────────────────────────────────────────────
  check('одна буква ничего не ищет', searchDrugs(книга, 'а').length === 0, 'иначе выпадет весь реестр')
  check('пустой запрос ничего не ищет', searchDrugs(книга, '   ').length === 0)

  const кард = searchDrugs(книга, 'кард').map((d) => d.n)
  check(
    'совпадение с начала важнее совпадения в середине',
    кард[0] === 'Кардиомагнил',
    `получено: ${кард.join(', ')}`,
  )
  check('совпадение в середине тоже находится', кард.includes('Аспирин® Кардио'), кард.join(', '))

  check(
    'название со знаком находится без знака',
    searchDrugs(книга, 'аспирин кардио').some((d) => d.n === 'Аспирин® Кардио'),
  )
  check(
    'Престариум находится без буквы А',
    searchDrugs(книга, 'престариум')[0]?.n === 'Престариум® А',
  )
  check('поиск нечувствителен к регистру', searchDrugs(книга, 'ЛОЗАР')[0]?.n === 'Лозартан')

  check('предел выдачи соблюдается', searchDrugs(книга, 'а', 3).length <= 3)
  const много = searchDrugs(книга, 'таблет', 2)
  check('по названию, а не по описанию', много.length === 0, 'иначе «таблетки» найдут всё подряд')

  // ── формы и дозировки ────────────────────────────────────────────────────
  const нурофен = книга[7]
  const варианты = variantsOf(нурофен, формы)
  check('варианты развёрнуты в названия форм', варианты.length === 3)
  check(
    'у каждой формы своя дозировка',
    варианты.find((v) => v.form === 'Гель для наружного применения')?.doses[0] === '5 %' &&
      варианты.find((v) => v.form === 'Капсулы')?.doses[0] === '200 мг',
    'общий список дозировок дал бы выбрать несуществующую пару вроде «капсулы 5 %»',
  )
  check('неизвестная форма отброшена', variantsOf({ n: 'Х', v: [[99, ['1 мг']]] }, формы).length === 0)
  check('препарат без вариантов не ломается', variantsOf({ n: 'Х' }, формы).length === 0)

  // ── подпись под названием ────────────────────────────────────────────────
  check('подпись собирает вещество и первую форму', describeDrug(книга[3], формы) === 'Лозартан · таблетки')
  check('подпись без формы не ломается', describeDrug({ n: 'Х', i: 'Игрек' }, формы) === 'Игрек')
  check('подпись без всего пустая', describeDrug({ n: 'Х' }, формы) === '')

  return failures
}
