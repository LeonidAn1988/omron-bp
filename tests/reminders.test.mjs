/**
 * Сборка напоминаний о приёме.
 *
 * Проверяется то, из-за чего напоминание молчит или врёт: слипание препаратов
 * по времени, устойчивость идентификатора при правке аптечки, препараты «по
 * потребности» и криво записанное время.
 */
import { buildReminders, countReminders, doseLine, minutesOfDay } from './build/api.mjs'

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const med = (over) => ({
    id: 'med-1', name: 'Лозартан', dose: '50 мг', left: 30, perDay: null, expires: null, ...over,
  })

  // ── разбор времени ───────────────────────────────────────────────────────
  check('обычное время', minutesOfDay('08:00') === 480)
  check('без ведущего нуля', minutesOfDay('8:05') === 485)
  check('конец суток', minutesOfDay('23:59') === 1439)
  check('часы за пределами суток отвергаются', minutesOfDay('24:00') === null)
  check('минуты за пределами часа отвергаются', minutesOfDay('10:60') === null)
  check('мусор отвергается', minutesOfDay('утром') === null)
  check('пробелы по краям не мешают', minutesOfDay(' 07:30 ') === 450)

  // ── строка препарата ─────────────────────────────────────────────────────
  check('название и дозировка', doseLine(med({ times: ['08:00'] })) === 'Лозартан 50 мг')
  check(
    'штуки указываются только когда их больше одной',
    doseLine(med({ perTime: 1 })) === 'Лозартан 50 мг' && doseLine(med({ perTime: 2 })) === 'Лозартан 50 мг — 2 шт.',
  )
  check('отношение к еде попадает в строку', doseLine(med({ meal: 'after' })) === 'Лозартан 50 мг — после еды')
  check(
    'штуки и еда вместе',
    doseLine(med({ perTime: 2, meal: 'before' })) === 'Лозартан 50 мг — 2 шт., до еды',
  )

  // ── сборка ───────────────────────────────────────────────────────────────
  const пусто = buildReminders([])
  check('пустая аптечка — пустой набор', пусто.length === 0)

  const поПотребности = buildReminders([med({ id: 'a', times: [] }), med({ id: 'b' })])
  check('препараты без расписания не напоминают', поПотребности.length === 0)

  const трое = buildReminders([
    med({ id: 'a', name: 'Аторвастатин', times: ['20:00'] }),
    med({ id: 'b', name: 'Метформин', times: ['08:00', '20:00'] }),
    med({ id: 'c', name: 'Периндоприл', times: ['08:00'] }),
  ])
  check('времён приёма два, а не пять', трое.length === 2, `получилось ${трое.length}`)
  check('порядок по времени', трое[0].hour === 8 && трое[1].hour === 20)
  check(
    'в восемь утра оба препарата в одном уведомлении',
    трое[0].body.split('\n').length === 2 && трое[0].body.includes('Метформин') && трое[0].body.includes('Периндоприл'),
    трое[0].body.replace(/\n/g, ' | '),
  )
  check('препараты внутри уведомления по алфавиту', трое[1].body.startsWith('Аторвастатин'), трое[1].body)
  check('заголовок называет время суток', трое[0].title === 'Утренний приём — 08:00', трое[0].title)
  check('вечер назван вечером', трое[1].title === 'Вечерний приём — 20:00', трое[1].title)

  // ── идентификаторы ───────────────────────────────────────────────────────
  check('идентификатор выведен из времени', трое[0].id === 800 && трое[1].id === 2000)
  const переименовано = buildReminders([
    med({ id: 'x', name: 'Другое название', times: ['08:00'] }),
  ])
  check(
    'правка аптечки не меняет идентификатор времени',
    переименовано[0].id === 800,
    'иначе старое напоминание осталось бы висеть в системе',
  )
  const все = buildReminders([
    med({ id: 'a', times: ['00:30'] }),
    med({ id: 'b', times: ['23:59'] }),
  ])
  check('идентификаторы уникальны', new Set(все.map((r) => r.id)).size === все.length)

  // ── крайние случаи ───────────────────────────────────────────────────────
  const дубль = buildReminders([med({ id: 'a', name: 'Лозартан', times: ['08:00', '08:00'] })])
  check('одно время дважды не задваивает препарат', дубль.length === 1 && дубль[0].body.split('\n').length === 1)

  const кривое = buildReminders([med({ id: 'a', times: ['08:00', 'вечером', '25:00'] })])
  check('нечитаемое время пропускается, остальное остаётся', кривое.length === 1 && кривое[0].hour === 8)

  check(
    'счётчик совпадает со сборкой',
    countReminders([med({ id: 'a', times: ['08:00', '14:00', '20:00'] })]) === 3,
  )

  const ночь = buildReminders([med({ id: 'a', times: ['03:00'] })])
  check('ночь названа ночью', ночь[0].title.startsWith('Ночной'), ночь[0].title)

  return failures
}
