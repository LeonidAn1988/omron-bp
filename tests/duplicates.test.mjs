/**
 * Одно вещество в двух коробках.
 *
 * Терапевт и кардиолог выписали одно и то же под разными торговыми именами.
 * Приложение сообщает факт о собственном списке человека — и только факт:
 * оценка («опасно», «отмените одно») перевела бы дневник в разряд медизделия.
 */
import { substances, sameSubstance, sameSubstanceText } from './build/api.mjs'

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }
  const мед = (id, name, inn) => ({ id, name, inn, dose: '', left: null, perDay: null, expires: null })

  // ── разбор строки вещества ──
  check('одиночное вещество', substances('Бисопролол').join('|') === 'бисопролол')
  check('комбинация через плюс', substances('Амлодипин + Периндоприл').join('|') === 'амлодипин|периндоприл')
  check('комбинация через запятую', substances('амлодипин, индапамид').join('|') === 'амлодипин|индапамид')
  check('скобки выбрасываются', substances('Ацетилсалициловая кислота (Аспирин)').join('|') === 'ацетилсалициловая кислота')
  check('пусто — ничего', substances(undefined).length === 0 && substances('').length === 0)
  check('мусор короче четырёх букв не берём', substances('А + Бисопролол').join('|') === 'бисопролол')

  // ── сведение аптечки ──
  const аптечка = [
    мед('m1', 'Конкор', 'Бисопролол'),
    мед('m2', 'Бисопролол-Тева', 'Бисопролол'),
    мед('m3', 'Метформин', 'Метформин'),
  ]
  const найдено = sameSubstance(аптечка)
  check('обе коробки помечены', найдено.has('m1') && найдено.has('m2'))
  check('одиночка не помечена', !найдено.has('m3'))
  check('видно, с чем совпало', найдено.get('m1').others.join('|') === 'Бисопролол-Тева')
  check('видно, какое вещество', найдено.get('m1').substance === 'бисопролол')

  // Главный случай: вещество приходит и отдельно, и внутри комбинации.
  const скомбинацией = sameSubstance([
    мед('k1', 'Амлодипин', 'Амлодипин'),
    мед('k2', 'Престанс', 'Амлодипин + Периндоприл'),
  ])
  check('комбинация сводится с одиночным', скомбинацией.has('k1') && скомбинацией.has('k2'))
  check('общее вещество названо верно', скомбинацией.get('k1').substance === 'амлодипин')

  // Три коробки одного вещества: перечисляем все.
  const трое = sameSubstance([
    мед('t1', 'Конкор', 'Бисопролол'),
    мед('t2', 'Бидоп', 'Бисопролол'),
    мед('t3', 'Нипертен', 'бисопролол'),
  ])
  check('регистр не мешает', трое.size === 3)
  check('перечислены оба соседа', трое.get('t1').others.length === 2)

  // Две пачки одного препарата: веществом совпадают, но пункт не про них —
  // «вещество то же, что у „Конкор“» на карточке самого Конкора запутает.
  const дветакие = sameSubstance([мед('p1', 'Конкор', 'Бисопролол'), мед('p2', 'Конкор®', 'Бисопролол')])
  check('две пачки одного препарата не помечаем', дветакие.size === 0)
  const смешанно = sameSubstance([
    мед('s1', 'Конкор', 'Бисопролол'),
    мед('s2', 'Конкор', 'Бисопролол'),
    мед('s3', 'Бидоп', 'Бисопролол'),
  ])
  check('но настоящего соседа находим', смешанно.get('s3').others.join('|') === 'Конкор', String(смешанно.get('s3')?.others))
  check('имя в перечислении не повторяется', смешанно.get('s3').others.length === 1)

  check('без вещества не сводим', sameSubstance([мед('x1', 'Что-то', undefined), мед('x2', 'Другое', undefined)]).size === 0)

  // ── текст ──
  const текст = sameSubstanceText(найдено.get('m1'))
  check('текст называет соседа и вещество', /Бисопролол-Тева/.test(текст) && /бисопролол/.test(текст))
  check('в тексте нет оценки и совета', !/опасн|отмен|нельзя|прекрат/i.test(текст), текст)

  return failures
}
